#!/usr/bin/env node
/**
 * Precompile JSON-Schema validators with AJV's `standalone` mode and bundle
 * them into self-contained CommonJS modules.
 *
 * Why: the renderer eagerly imports `coreCatalog`, which calls AJV's
 * runtime `compile(schema)` → `new Function(…)`. Strict CSP forbids
 * `'unsafe-eval'`, so the live `ajv.compile` path can't run in the
 * Electron renderer or any production-CSP web deploy. AJV's standalone
 * mode emits a self-contained CommonJS module whose validator function is
 * plain code (no Function constructor) — safe under strict CSP.
 *
 * But: AJV's standalone output still `require()`s its runtime helpers
 * (`ajv/dist/runtime/ucs2length`) and, when the schema uses formats,
 * `require("ajv-formats/dist/formats")`. Angular's ESM bundler refuses to
 * resolve those dynamic CJS requires at runtime ("Dynamic require of X is
 * not supported"). The fix: bundle the standalone CJS through esbuild so
 * those internal requires are inlined into one file. The output then has
 * zero external runtime deps, which lets the Angular ESM bundle import it
 * cleanly.
 *
 * Run via `pnpm precompile:validators` after editing either schema. The
 * generated files are committed; CI re-runs this script and `git diff
 * --exit-code`s to fail loudly on a schema edit without regen.
 */

import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import Ajv from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';
import standaloneCode from 'ajv/dist/standalone/index.js';
import * as esbuild from 'esbuild';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, '..');

const TARGETS = [
  {
    schema: 'libs/domain/catalog/src/schema/catalog-entry.schema.json',
    out: 'libs/domain/catalog/src/validator.generated.cjs',
    label: 'CatalogEntry',
  },
  {
    schema: 'libs/domain/document/src/schema/aqua-document.schema.json',
    out: 'libs/domain/document/src/validator.generated.cjs',
    label: 'AquaDocument',
  },
];

const BANNER = `// AUTO-GENERATED by tools/precompile-validators.mjs — do NOT edit by hand.
// AJV standalone code for the JSON Schema next door, bundled via esbuild so
// every runtime dependency (ajv/dist/runtime/*, ajv-formats/dist/formats)
// is inlined and the consumer never has to resolve a CJS \`require()\` at
// runtime. Re-run \`pnpm precompile:validators\` if you edit the schema.
//
// This file is committed so consumers don't need to run codegen to build
// the lib. CI re-runs the precompile step and \`git diff --exit-code\`s to
// fail loudly on a schema edit without regen.
/* eslint-disable */
`;

async function precompile(target) {
  const schemaPath = resolve(REPO, target.schema);
  const outPath = resolve(REPO, target.out);
  const schemaJson = JSON.parse(await readFile(schemaPath, 'utf8'));

  // `code: { source: true, esm: false }` is the load-bearing pair —
  // `source: true` makes AJV remember the generated code so `standalone-
  // Code` can emit it as a string; `esm: false` keeps the output CJS so
  // it loads under `require()` and matches the workspace's CommonJS libs.
  const ajv = new Ajv.default({
    allErrors: true,
    strict: true,
    code: { source: true, esm: false },
  });
  addFormats.default(ajv);
  const validate = ajv.compile(schemaJson);
  const standaloneSource = standaloneCode.default(ajv, validate);

  // Bundle through esbuild so its internal `require()`s for ajv-formats /
  // ajv runtime helpers get inlined. Target Node-compatible CJS so the
  // output is loadable from both ts-jest (Node) and Angular's esbuild
  // bundle (ESM consumer importing CJS).
  //
  // The scratch file MUST live inside the workspace so Node module
  // resolution finds `ajv` / `ajv-formats` via the workspace's
  // node_modules. esbuild walks parent directories looking for
  // node_modules; placing the entry in /tmp would skip the workspace
  // entirely and fail on `ajv/dist/runtime/ucs2length` because the
  // package.json `exports` field only lists subpaths the publisher chose.
  // Once inside the workspace, esbuild's module resolution mirrors Node's
  // and the standalone requires resolve cleanly.
  const scratchRoot = resolve(REPO, 'node_modules/.cache/aquascape-validators');
  const scratch = await mkdtemp(join(scratchRoot, '/'));
  const entry = join(scratch, 'entry.cjs');
  await writeFile(entry, standaloneSource, 'utf8');
  try {
    const built = await esbuild.build({
      entryPoints: [entry],
      bundle: true,
      platform: 'node',
      format: 'cjs',
      target: ['es2020'],
      write: false,
      logLevel: 'silent',
      absWorkingDir: REPO,
    });
    const bundled = built.outputFiles[0].text;
    await writeFile(outPath, `${BANNER}\n${bundled}\n`, 'utf8');
  } finally {
    await rm(scratch, { recursive: true, force: true });
  }

  console.log(`  ✓ ${target.label} → ${target.out}`);
}

(async () => {
  console.log('precompile-validators: emitting standalone AJV code + esbuild bundle');
  for (const t of TARGETS) {
    await precompile(t);
  }
  console.log('done.');
})().catch((err) => {
  console.error('precompile-validators failed:', err);
  process.exit(1);
});
